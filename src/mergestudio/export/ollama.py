"""Export generators for Ollama Modelfile and GGUF quantization toolkits."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional


def generate_ollama_modelfile(
    model_dir: Path,
    system_prompt: str = "You are a helpful, knowledgeable AI assistant.",
) -> Path:
    """Generate a production ready Ollama Modelfile from merged model configurations."""
    model_dir = Path(model_dir)
    modelfile_path = model_dir / "Modelfile"

    # Inspect tokenizer and model config
    tokenizer_cfg = {}
    tok_file = model_dir / "tokenizer_config.json"
    if tok_file.exists():
        with open(tok_file, "r", encoding="utf-8") as f:
            tokenizer_cfg = json.load(f)

    chat_template = tokenizer_cfg.get("chat_template", "")
    stop_tokens = _detect_stop_tokens(tokenizer_cfg)

    template_str = _resolve_ollama_template(chat_template)

    lines = [
        f"# Generated by MergeStudio v0.1.0",
        f"FROM ./model.safetensors",
        f"",
        f'SYSTEM """{system_prompt}"""',
        f"",
        f'TEMPLATE """{template_str}"""',
        f"",
        f"PARAMETER temperature 0.7",
        f"PARAMETER top_p 0.9",
        f"PARAMETER top_k 40",
    ]

    for stop in stop_tokens:
        lines.append(f'PARAMETER stop "{stop}"')

    modelfile_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return modelfile_path


def generate_gguf_conversion_script(model_dir: Path) -> Path:
    """Generate conversion and quantization shell script for llama.cpp and Ollama."""
    model_dir = Path(model_dir)
    script_path = model_dir / "quantize_model.sh"

    script_content = f"""#!/usr/bin/env bash
# MergeStudio: GGUF Conversion and Quantization Helper
set -e

MODEL_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
echo "=== Step 1: Converting Hugging Face Safetensors to GGUF F16 ==="
python llama.cpp/convert_hf_to_gguf.py "$MODEL_DIR" --outfile "$MODEL_DIR/model-f16.gguf"

echo "=== Step 2: Quantizing to Q4_K_M (Recommended 4-bit) ==="
./llama.cpp/llama-quantize "$MODEL_DIR/model-f16.gguf" "$MODEL_DIR/model-q4_k_m.gguf" Q4_K_M

echo "=== Step 3: Registering with Ollama ==="
sed -i 's|FROM ./model.safetensors|FROM ./model-q4_k_m.gguf|g' "$MODEL_DIR/Modelfile"
ollama create merged-model -f "$MODEL_DIR/Modelfile"

echo "Done! Run your merged model with: ollama run merged-model"
"""
    script_path.write_text(script_content, encoding="utf-8")
    return script_path


def _detect_stop_tokens(tokenizer_cfg: Dict[str, Any]) -> List[str]:
    """Identify stop tokens from tokenizer configurations."""
    stops = []
    eos = tokenizer_cfg.get("eos_token")
    if isinstance(eos, str) and eos:
        stops.append(eos)
    elif isinstance(eos, dict) and "content" in eos:
        stops.append(eos["content"])

    # Common modern stop tokens
    candidates = ["<|eot_id|>", "<|im_end|>", "<|end_of_text|>", "</s>"]
    for c in candidates:
        if c not in stops:
            stops.append(c)

    return stops[:4]


def _resolve_ollama_template(chat_template: str) -> str:
    """Translate or map Jinja chat templates to Go template syntax for Ollama."""
    if "<|start_header_id|>" in chat_template or "start_header_id" in chat_template:
        # Llama-3 format
        return (
            "{{ if .System }}<|start_header_id|>system<|end_header_id|>\n\n"
            "{{ .System }}<|eot_id|>{{ end }}"
            "{{ if .Prompt }}<|start_header_id|>user<|end_header_id|>\n\n"
            "{{ .Prompt }}<|eot_id|>{{ end }}"
            "<|start_header_id|>assistant<|end_header_id|>\n\n"
            "{{ .Response }}<|eot_id|>"
        )
    elif "<|im_start|>" in chat_template or "im_start" in chat_template:
        # ChatML format
        return (
            "{{ if .System }}<|im_start|>system\n"
            "{{ .System }}<|im_end|>\n{{ end }}"
            "{{ if .Prompt }}<|im_start|>user\n"
            "{{ .Prompt }}<|im_end|>\n{{ end }}"
            "<|im_start|>assistant\n"
            "{{ .Response }}<|im_end|>"
        )

    # Standard default
    return (
        "{{ if .System }}{{ .System }}\n\n{{ end }}"
        "{{ if .Prompt }}User: {{ .Prompt }}\n\n{{ end }}"
        "Assistant: {{ .Response }}"
    )
